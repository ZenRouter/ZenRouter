#!/usr/bin/env node
// Build-only registry import. The generated runtime module has no dependencies.
import { readFileSync, writeFileSync } from "node:fs";
import REGISTRY from "../open-sse/providers/registry/index.js";

const identities = { el: "elevenlabs", jina: "jina-ai", "jina-ai": "jina-ai", polly: "aws-polly", "aws-polly": "aws-polly" };
const storage = {};
const upstream = {};
const canonicalIds = new Set(REGISTRY.map(provider => provider.id));
for (const provider of REGISTRY) {
  for (const token of [provider.id, provider.alias, provider.uiAlias, ...(provider.aliases || [])].filter(Boolean)) {
    // Canonical IDs take precedence over aliases (the registry contains legacy mmf).
    if (token !== provider.id && canonicalIds.has(token)) continue;
    if (Object.hasOwn(identities, token) && identities[token] !== provider.id) throw new Error(`Conflicting provider identity: ${token}`);
    identities[token] = provider.id;
  }
  storage[provider.id] = provider.alias || provider.id;
  for (const model of provider.models || []) {
    if (!model.upstreamModelId || model.upstreamModelId === model.id) continue;
    const models = upstream[provider.id] ||= {};
    if (Object.hasOwn(models, model.id) && models[model.id] !== model.upstreamModelId) throw new Error(`Conflicting upstream identity: ${provider.id}/${model.id}`);
    models[model.id] = model.upstreamModelId;
  }
}
const sorted = (value) => Object.fromEntries(Object.keys(value).sort().map(key => [key, typeof value[key] === "object" ? sorted(value[key]) : value[key]]));
const literal = (value) => JSON.stringify(sorted(value), null, 2);
const source = `// Generated by scripts/generate-provider-identity.mjs. Do not edit by hand.
// Metadata identities only: never rewrite a custom identifier or a wire model ID.
export const PROVIDER_IDENTITIES = ${literal(identities)};

export const PROVIDER_STORAGE_ALIASES = ${literal(storage)};

export const DECLARED_UPSTREAM_MODEL_IDS = ${literal(upstream)};

export function canonicalizeProviderId(provider) {
  return Object.hasOwn(PROVIDER_IDENTITIES, provider) ? PROVIDER_IDENTITIES[provider] : provider;
}

// Exact requested token first so independently saved overrides retain their choice.
export function getProviderIdentityTokens(provider) {
  const canonical = canonicalizeProviderId(provider);
  return [...new Set([provider, canonical, ...Object.keys(PROVIDER_IDENTITIES).filter(token => PROVIDER_IDENTITIES[token] === canonical)])];
}

export function getDeclaredUpstreamModelId(provider, model) {
  const canonical = canonicalizeProviderId(provider);
  const models = Object.hasOwn(DECLARED_UPSTREAM_MODEL_IDS, canonical) ? DECLARED_UPSTREAM_MODEL_IDS[canonical] : null;
  return models && Object.hasOwn(models, model) ? models[model] : model;
}
`;
const target = new URL("../open-sse/providers/identity.js", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8") !== source) {
    console.error("Provider identity metadata is stale; run node scripts/generate-provider-identity.mjs");
    process.exitCode = 1;
  }
} else {
  writeFileSync(target, source);
}
